import Foundation

/// Карточка «Мысль дня» на главном экране. Требование из критериев
/// приёмки: одна и та же фраза не повторяется чаще раза в две недели —
/// детерминированный перебор по дню года это обеспечивает.
///
/// Фразы разложены по целям из 4-го вопроса онбординга: ответ там больше
/// не «уходит в никуда», а определяет, какие мысли человек видит каждый
/// день. Тон везде один — поддержка без обещаний и без обесценивания.
///
/// TODO: копирайт написан в согласованном тоне (без токсичного позитива и
/// диагностических формулировок), но психологом/копирайтером ещё не
/// утверждён — в отличие от `CourseCatalog`. Заменить перед релизом.
enum QuoteOfTheDay {
    private static let shared = [
        "Не обязательно быть идеальным, чтобы быть достойным любви.",
        "Маленький шаг сегодня — это тоже шаг.",
        "Прогресс не обязан быть прямой линией.",
        "Отдых — тоже часть заботы о себе.",
        "Ошибки — это данные, а не приговор.",
        "Ты — это не одна твоя худшая мысль о себе.",
        "Не всё нужно решать сегодня.",
        "Замечать свои чувства — уже забота о себе.",
    ]

    private static let byGoal: [OnboardingGoal: [String]] = [
        .confidence: [
            "Уверенность — это навык, а не черта характера.",
            "Можно сомневаться и всё равно сделать шаг.",
            "Ты уже проходил(а) через трудное раньше — это тоже опыт.",
            "Смелость — это не отсутствие страха, а действие рядом с ним.",
            "Право занимать место у тебя есть по умолчанию.",
        ],
        .lessCritical: [
            "Внутренний критик — это мысль, а не факт о тебе.",
            "Ты можешь говорить с собой так же, как с другом.",
            "Строгость к себе не делает результат лучше — она делает путь тяжелее.",
            "Заметить критику — уже половина работы с ней.",
            "Сравнение с другими редко говорит правду о тебе.",
        ],
        .anxietyEase: [
            "Тревога говорит «опасно», но не она решает, что делать дальше.",
            "Дыхание — самый короткий путь к телу, когда мысли разогнались.",
            "Не обязательно верить каждой тревожной мысли.",
            "Можно делать маленькое дело, даже если тревожно.",
            "То, что ты чувствуешь сейчас, изменится — чувства не постоянны.",
        ],
        .selfWorth: [
            "Твоя ценность не зависит от того, сколько ты успел(а) сегодня.",
            "Быть неидеальным и быть достаточным — это не противоречие.",
            "Ты имеешь право на заботу просто потому, что ты есть.",
            "Полезность — не единственная причина ценить себя.",
            "Ты можешь быть добрым(ой) к себе даже в трудный день.",
        ],
        .other: [
            "Ты можешь идти в своём темпе.",
            "Каждый день практики немного меняет то, как ты с собой разговариваешь.",
            "Начать заново — это тоже движение вперёд.",
        ],
    ]

    static func current(referenceDate: Date = .now, goal: OnboardingGoal? = nil) -> String {
        let pool: [String]
        if let goal, let goalQuotes = byGoal[goal] {
            pool = goalQuotes + shared
        } else {
            pool = shared
        }
        let dayOfYear = Calendar.current.ordinality(of: .day, in: .year, for: referenceDate) ?? 1
        return pool[dayOfYear % pool.count]
    }
}
